"""Spy box helper: the routine steps in one place.

  python tools/spy.py join              build spy/gala.gd from spy_src/gala/*.gd (test and ship do this first)
  python tools/spy.py test [SECTIONS]   party tests (all, or e.g. items,mission); car tests with: test car
  python tools/spy.py voices            record every line in spy/voice/lines.json that's missing or changed
  python tools/spy.py ship VERSION "commit message"
                                        set the version, export, install on the phone (must be plugged in),
                                        launch, check for script errors, then commit and push

Sections: core chat heat gun english items mission exit (see spy/gala_test.gd).
"""
import asyncio, json, os, pathlib, re, subprocess, sys, time

sys.stdout.reconfigure(encoding="utf-8")
ROOT = pathlib.Path(__file__).resolve().parent.parent
SPY = ROOT / "spy"
BUILD = ROOT / "build"
GODOT = pathlib.Path.home() / "Downloads/Godot_v4.7.2-stable_win64.exe/Godot_v4.7.2-stable_win64_console.exe"
ADB = pathlib.Path.home() / "AppData/Local/Android/Sdk/platform-tools/adb.exe"
APK = BUILD / "spy.apk"
PKG = "com.kopus123.spy"
COAUTHOR = "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"

# who sounds like what (edge-tts): voice, pitch, rate
IJ, HS, SH = "ko-KR-InJoonNeural", "ko-KR-HyunsuMultilingualNeural", "ko-KR-SunHiNeural"
VOICES = {
    "host": (IJ, "-6Hz", "-5%"), "broker": (IJ, "-22Hz", "-15%"), "assistant": (SH, "+0Hz", "-5%"),
    "g1": (SH, "-10Hz", "-5%"), "g2": (HS, "+10Hz", "+0%"), "g3": (IJ, "+12Hz", "+5%"), "g4": (SH, "+6Hz", "+5%"),
    "g5": (HS, "+0Hz", "-5%"), "g6": (SH, "-4Hz", "-10%"), "security": (HS, "-16Hz", "-5%"), "bartender": (SH, "+16Hz", "+0%"),
    "buyer": (HS, "-8Hz", "+0%"), "handler": (HS, "+0Hz", "-5%"), "me": (IJ, "+0Hz", "-10%"),
}


def run(cmd, timeout=600, quiet=False):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=timeout)
    if not quiet and r.returncode != 0: print(r.stdout[-2000:], r.stderr[-2000:])
    return r


SRC = ROOT / "spy_src" / "gala"
STAMP = BUILD / ".gala_joined"
HEAD = "# GENERATED by tools/spy.py join from spy_src/gala/*.gd. Edit those files, not this one.\n"


def join(args=None):   # the party's code lives in parts; Godot gets them joined into one script
    import hashlib
    gd = SPY / "gala.gd"
    if gd.exists() and STAMP.exists() and hashlib.md5(gd.read_bytes()).hexdigest() != STAMP.read_text().strip():
        print("spy/gala.gd was changed by hand since the last join: move that change into spy_src/gala/ first"); return 1
    parts = sorted(SRC.glob("*.gd"))
    text = HEAD + "\n\n".join(f.read_text(encoding="utf-8").rstrip("\n") for f in parts) + "\n"
    gd.write_text(text, encoding="utf-8")
    STAMP.write_text(hashlib.md5(gd.read_bytes()).hexdigest())
    return 0


def need_import():   # new sound files Godot hasn't seen yet
    return any(not pathlib.Path(str(f) + ".import").exists() for f in SPY.glob("voice/**/*.mp3"))


def test(args):
    if join(): return 1
    if need_import():
        print("importing new files…"); run([GODOT, "--headless", "--path", SPY, "--import"], quiet=True)
    which = args[0] if args else ""
    if which == "car": cmd = [GODOT, "--path", SPY, "--", "--test"]
    else: cmd = [GODOT, "--path", SPY, "res://gala_test.tscn", "--", "--test" + ("=" + which if which else "")]
    t0 = time.time()
    try: r = run(cmd, timeout=400, quiet=True); out = r.stdout + r.stderr
    except subprocess.TimeoutExpired as e: out = (e.stdout or b"").decode("utf-8", "replace") + "\nTIMED OUT"
    (BUILD / "test_last.log").write_text(out, encoding="utf-8")
    keep = [l for l in out.splitlines() if l.startswith(("FAIL", "DONE", "== ", "TIMED")) or "SCRIPT ERROR" in l or "Parse Error" in l]
    print("\n".join(keep)); print("(%.0f s; full log: build/test_last.log)" % (time.time() - t0))
    return 0 if any(l.startswith("DONE 0 failed") for l in keep) else 1


def voices(args):
    import edge_tts
    table = json.loads((SPY / "voice" / "lines.json").read_text(encoding="utf-8"))
    done_f = SPY / "voice" / ".lines_done.json"
    done = json.loads(done_f.read_text(encoding="utf-8")) if done_f.exists() else {}
    todo = []
    for path, (who, text) in table.items():
        f = SPY / "voice" / (path + ".mp3")
        key = who + "|" + text
        if f.exists() and path not in done: done[path] = key; continue   # recorded before this tool: leave it be
        if not f.exists() or done.get(path) != key: todo.append((path, who, text))

    async def one(path, who, text):
        v = VOICES[who]; f = SPY / "voice" / (path + ".mp3")
        f.parent.mkdir(parents=True, exist_ok=True)
        for a in range(6):
            try:
                await edge_tts.Communicate(text, v[0], pitch=v[1], rate=v[2]).save(str(f))
                if f.stat().st_size > 1000: done[path] = who + "|" + text; return
            except Exception: pass
            await asyncio.sleep(2 + a * 2)
        print("FAILED", path)

    async def main():
        for i in range(0, len(todo), 6): await asyncio.gather(*(one(*j) for j in todo[i:i + 6]))
    asyncio.run(main())
    done_f.write_text(json.dumps(done, ensure_ascii=False, indent=1), encoding="utf-8")
    print("recorded %d line(s)" % len(todo) + ("" if not todo else ": " + ", ".join(t[0] for t in todo)))
    return 0


def ship(args):
    if len(args) < 2: print('usage: ship VERSION "commit message"'); return 1
    ver, msg = args[0], args[1]
    if join(): return 1
    p = SPY / "export_presets.cfg"
    p.write_text(re.sub(r'version/name="[^"]*"', 'version/name="%s"' % ver, p.read_text(encoding="utf-8")), encoding="utf-8")
    print("exporting", ver, "…")
    r = run([GODOT, "--headless", "--path", SPY, "--export-debug", "Android", APK], timeout=600, quiet=True)
    if not APK.exists() or time.time() - APK.stat().st_mtime > 120: print("export failed:\n", r.stdout[-1500:], r.stderr[-1500:]); return 1
    env = dict(os.environ, MSYS_NO_PATHCONV="1")
    devs = [l for l in run([ADB, "devices"], quiet=True).stdout.splitlines()[1:] if l.strip().endswith("device")]
    if not devs: print("no phone connected: plug it in and run ship again"); return 1
    print("installing on", devs[0].split()[0], "…")
    if "Success" not in run([ADB, "install", "-r", APK], timeout=300, quiet=True).stdout: print("install failed"); return 1
    run([ADB, "logcat", "-c"], quiet=True)
    run([ADB, "shell", "am", "start", "-n", PKG + "/com.godot.game.GodotAppLauncher"], quiet=True)
    time.sleep(7)
    got = re.search(r"versionName=(\S+)", run([ADB, "shell", "dumpsys", "package", PKG], quiet=True).stdout)
    log = run([ADB, "logcat", "-d"], quiet=True).stdout
    errs = [l for l in log.splitlines() if "SCRIPT ERROR" in l]
    print("on the phone:", got.group(1) if got else "?", "·", len(errs), "script error(s)")
    for l in errs[:5]: print("  ", l.split("godot   :")[-1].strip())
    run(["git", "-C", ROOT, "add", "-A", "spy", "spy_src", "tools"], quiet=True)
    c = run(["git", "-C", ROOT, "commit", "-q", "-m", msg + "\n\n" + COAUTHOR], quiet=True)
    if c.returncode == 0:
        run(["git", "-C", ROOT, "push", "-q", "origin", "main"], timeout=120, quiet=True)
        print("committed and pushed:", run(["git", "-C", ROOT, "log", "--oneline", "-1"], quiet=True).stdout.strip())
    else: print("nothing new to commit")
    return 0 if not errs else 2


if __name__ == "__main__":
    cmds = {"join": join, "test": test, "voices": voices, "ship": ship}
    if len(sys.argv) < 2 or sys.argv[1] not in cmds: print(__doc__); sys.exit(1)
    sys.exit(cmds[sys.argv[1]](sys.argv[2:]))
